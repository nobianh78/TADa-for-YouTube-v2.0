# TADa for YouTube - PowerShell Bundle Script
# Bundles modular content scripts from modules/ into contentScript.js

$ErrorActionPreference = "Stop"

$modules = @(
  "modules\core.js",
  "modules\adBlocker.js",
  "modules\uiLayout.js",
  "modules\volumeBooster.js",
  "modules\ambientLight.js",
  "modules\playerTools.js",
  "modules\videoFilter.js",
  "modules\cinemaMode.js",
  "modules\customLoader.js",
  "modules\qualityController.js",
  "modules\abLooper.js",
  "modules\bookmarks.js",
  "modules\returnDislike.js",
  "modules\sponsorBlock.js",
  "modules\orchestrator.js"
)

$targetFile = Join-Path $PSScriptRoot "contentScript.js"
Write-Host "[TADa Build] Bundling modules into contentScript.js..." -ForegroundColor Cyan

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("/**")
[void]$sb.AppendLine(" * TADa for YouTube - Content Script Bundle")
[void]$sb.AppendLine(" * Generated from modules/ - DO NOT EDIT THIS FILE DIRECTLY")
[void]$sb.AppendLine(" * Edit files in modules/ and run 'bundle.ps1' or 'node build.js'")
[void]$sb.AppendLine(" */")
[void]$sb.AppendLine("")

foreach ($rel in $modules) {
  $abs = Join-Path $PSScriptRoot $rel
  if (-not (Test-Path $abs)) {
    Write-Error "[TADa Build] Error: File not found: $rel"
    exit 1
  }
  $content = [System.IO.File]::ReadAllText($abs, [System.Text.Encoding]::UTF8)
  [void]$sb.AppendLine("/* ======================================================= */")
  [void]$sb.AppendLine("/* [MODULE] $($rel -replace '\\', '/') */")
  [void]$sb.AppendLine("/* ======================================================= */")
  [void]$sb.AppendLine("")
  [void]$sb.AppendLine($content.Trim())
  [void]$sb.AppendLine("")
  [void]$sb.AppendLine("")
}

$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($targetFile, $sb.ToString(), $utf8NoBom)

Write-Host "[TADa Build] Successfully built $targetFile ($($sb.Length) bytes, $($modules.Count) modules)" -ForegroundColor Green

# Optional packing
if ($args -contains "--zip" -or $args -contains "pack") {
  $zipPath = Join-Path (Split-Path $PSScriptRoot -Parent) "extensionTADa-cws.zip"
  if (Test-Path $zipPath) { Remove-Item -Force $zipPath }
  & tar.exe -a -c -f $zipPath manifest.json background.js antiBot.js storageSanitizer.js earlyPatch.js contentScript.js popup.html popup.css popup.js rules/rules_1.json icons
  Write-Host "[TADa Build] Clean CWS ZIP created at: $zipPath" -ForegroundColor Green
}
