/**
 * Build script for TADa for YouTube
 * Bundles modular content scripts from modules/ into contentScript.js
 */

const fs = require("fs");
const path = require("path");

const MODULE_FILES = [
  "modules/core.js",
  "modules/adBlocker.js",
  "modules/uiLayout.js",
  "modules/volumeBooster.js",
  "modules/ambientLight.js",
  "modules/playerTools.js",
  "modules/videoFilter.js",
  "modules/cinemaMode.js",
  "modules/customLoader.js",
  "modules/qualityController.js",
  "modules/abLooper.js",
  "modules/bookmarks.js",
  "modules/returnDislike.js",
  "modules/sponsorBlock.js",
  "modules/orchestrator.js"
];

const TARGET_FILE = path.join(__dirname, "contentScript.js");

console.log("[TADa Build] Bundling modules into contentScript.js...");

let bundleContent = `/**
 * TADa for YouTube - Content Script Bundle
 * Generated from modules/ - DO NOT EDIT THIS FILE DIRECTLY
 * Edit files in modules/ and run 'node build.js'
 */

`;

for (const relPath of MODULE_FILES) {
  const absPath = path.join(__dirname, relPath);
  if (!fs.existsSync(absPath)) {
    console.error(`[TADa Build] Error: File not found: ${relPath}`);
    process.exit(1);
  }
  const content = fs.readFileSync(absPath, "utf8");
  bundleContent += `\n/* ======================================================= */\n`;
  bundleContent += `/* [MODULE] ${relPath} */\n`;
  bundleContent += `/* ======================================================= */\n\n`;
  bundleContent += content.trim();
  bundleContent += `\n\n`;
}

fs.writeFileSync(TARGET_FILE, bundleContent, "utf8");
console.log(`[TADa Build] Successfully built ${TARGET_FILE} (${bundleContent.length} bytes, ${MODULE_FILES.length} modules)`);

if (process.argv.includes("--zip") || process.argv.includes("pack")) {
  const { execSync } = require("child_process");
  const zipPath = path.join(__dirname, "..", "extensionTADa-cws.zip");
  if (fs.existsSync(zipPath)) fs.unlinkSync(zipPath);
  execSync(
    "zip -r ../extensionTADa-cws.zip manifest.json background.js antiBot.js storageSanitizer.js earlyPatch.js contentScript.js popup.html popup.css popup.js rules/rules_1.json icons/*.png",
    { cwd: __dirname, stdio: "inherit" }
  );
  console.log(`[TADa Build] Clean CWS ZIP created at: ${zipPath}`);
}
